from collections.abc import Sequence

from spacy.tokens import Doc
from spacy.vocab import Vocab

TokenObservation = tuple[str, str, str, str, str, int, str, str]


def observed_doc(tokens: Sequence[TokenObservation]) -> Doc:
    """Recreate the token attributes consumed by extraction policy."""
    doc = Doc(
        Vocab(),
        words=[token[0] for token in tokens],
        spaces=[False] * len(tokens),
        pos=[token[1] for token in tokens],
        tags=[token[2] for token in tokens],
        lemmas=[token[3] for token in tokens],
        heads=[token[5] for token in tokens],
        deps=[token[6] for token in tokens],
        morphs=[token[7] for token in tokens],
    )
    for token, observation in zip(doc, tokens, strict=True):
        token.norm_ = observation[4]
    return doc


